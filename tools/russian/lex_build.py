def times(n):
    n = int(n)
    if n % 10 == 1 and n % 100 != 11:
        return f'{n} раза'
    return f'{n} раз'

def books(n):
    n = int(n)
    if n % 10 == 1 and n % 100 != 11:
        return f'{n} книге'
    return f'{n} книгах'

USE_RE = re.compile(r'^Used about (\d+) times in the (New|Old) Testament, in (\d+) books? — first in (.+?) (\d+:\d+); most often in (.+)\.$')

def book(name):
    return BOOKS[name]

def tr_use(u):
    m = USE_RE.match(u)
    assert m, u
    n, test, nb, fbook, fref, most = m.groups()
    testament = 'Новом Завете' if test == 'New' else 'Ветхом Завете'
    items = re.findall(r'((?:\d )?[A-Z][A-Za-z ]*?) \((\d+)\)', most)
    parts = [f'{book(b)} ({c})' for b, c in items]
    if len(parts) > 1:
        most_ru = ', '.join(parts[:-1]) + ' и ' + parts[-1]
    else:
        most_ru = parts[0]
    return (f'Встречается в {testament} около {times(n)}, в {books(nb)}. '
            f'Впервые: {book(fbook)} {fref}; чаще всего: {most_ru}.')

